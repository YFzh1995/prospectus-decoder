class Inspect(HTMLParser):
    def __init__(self):
        super().__init__();self.ids=[];self.links=[];self.stack=[];self.author_in_notes=None;self.numeric_reference=False;self.external_assets=[];self.in_footer=False;self.in_notes=False
    def handle_starttag(self,tag,attrs):
        a=dict(attrs)
        if 'id'in a:self.ids.append(a['id'])
        if tag=='a':
            self.links.append(a.get('href',''));self.numeric_reference |= 'reference' in a.get('class','').split()
        if tag=='details':self.in_notes=True
        if tag=='footer':self.author_in_notes=self.in_notes;self.in_footer=True
        if tag in ['script','link'] and (a.get('src') or a.get('href')):self.external_assets.append(a)
    def handle_endtag(self,tag):
        if tag=='details':self.in_notes=False
        if tag=='footer':self.in_footer=False

