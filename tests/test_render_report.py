class RendererTest(unittest.TestCase):
    def render(self,source):
        with TemporaryDirectory() as d:
            p=Path(d)/'report.md';p.write_text(source);out=p.with_suffix('.html');renderer.render(p,out);return out.read_text()
    def test_navigation_citations_author_and_safety(self):
        h=self.render(SAMPLE);ins=Inspect();ins.feed(h)
        self.assertEqual(len(ins.ids),len(set(ins.ids)))
        for target in ins.links:
            if target.startswith('#'):self.assertIn(target[1:],ins.ids)
        self.assertIn('section-1',ins.ids) # TOC removal must not swallow first content anchor.
        self.assertIn('note-1',ins.ids) # Adjacent anchor and paragraph must resolve.
        self.assertNotIn('PDANCHOR',h)
        self.assertTrue(ins.numeric_reference)
        self.assertFalse(ins.author_in_notes)
        self.assertIn('欢迎交流与反馈',h)
        self.assertIn('beforeprint',h)
        self.assertIn('notes.open=true',h)
        self.assertNotIn("<script>alert('untrusted')</script>",h)
        self.assertFalse(ins.external_assets)
    def test_duplicate_anchor_rejected(self):
        with self.assertRaises(ValueError):self.render(SAMPLE+'\n<a id="note-1"></a>\n')
    def test_generated_id_avoids_explicit_id_collision(self):
        h=self.render(SAMPLE.replace('id="section-1"','id="pd-heading-1"').replace('(#section-1)','(#pd-heading-1)'));ins=Inspect();ins.feed(h)
        self.assertEqual(len(ins.ids),len(set(ins.ids)))
    def test_report_without_sources_or_signature(self):
        h=self.render('# Short\n\n## Business\n\nA short report.\n');self.assertNotIn('<details',h);self.assertNotIn('<footer',h)
    def test_english_source_section_and_signature(self):
        h=self.render(SAMPLE.replace('资料、数据口径与附件','Sources').replace('报告由 Prospectus Decoder','Report generated by Prospectus Decoder'));ins=Inspect();ins.feed(h);self.assertFalse(ins.author_in_notes);self.assertIn('source-details',ins.ids)

